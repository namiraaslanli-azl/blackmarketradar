#!/usr/bin/env bash
# Black Market Radar — one-command install on a fresh Ubuntu 22.04/24.04 server.
#
#   git clone https://github.com/<owner>/<repo>.git /opt/radar && cd /opt/radar
#   sudo bash deploy/install.sh
#
# Safe to run again: it keeps an existing .env (passwords, API keys) and only
# rebuilds and restarts the services. Put the seed file (Excel or CSV) in
# data/import/ before running, or later run:  sudo bash deploy/install.sh --import
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT=$(pwd)
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
die() { printf '\n\033[31mXəta: %s\033[0m\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "root kimi işə salın: sudo bash deploy/install.sh"

# 1. Docker -----------------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  say "1/5 Docker quraşdırılır…"
  curl -fsSL https://get.docker.com | sh
else
  say "1/5 Docker artıq var."
fi
docker compose version >/dev/null 2>&1 || die "docker compose tapılmadı"

# Firewall: only SSH and web
if command -v ufw >/dev/null 2>&1; then
  ufw allow OpenSSH >/dev/null 2>&1 || true
  ufw allow 80/tcp >/dev/null 2>&1 || true
  ufw allow 443/tcp >/dev/null 2>&1 || true
  yes | ufw enable >/dev/null 2>&1 || true
fi

# 2. .env ------------------------------------------------------------------------
rand() { tr -dc 'A-Za-z0-9' </dev/urandom | head -c "${1:-32}"; }
if [ ! -f .env ]; then
  say "2/5 Ayarlar (.env) yaradılır"
  read -rp "Saytın domeni (məs. radar.example.com; boş buraxsanız IP ilə açılar): " DOMAIN
  read -rp "Giriş üçün istifadəçi adı [radar]: " AUTH_USER
  AUTH_USER=${AUTH_USER:-radar}
  while true; do
    read -rsp "Giriş şifrəsi (ən az 10 simvol): " AUTH_PASS; echo
    [ ${#AUTH_PASS} -ge 10 ] && break
    echo "Şifrə çox qısadır."
  done
  HASH=$(docker run --rm caddy:2-alpine caddy hash-password --plaintext "$AUTH_PASS")
  SITE=${DOMAIN:-:80}
  cat > .env <<EOF
# Generated by deploy/install.sh on $(date -u +%Y-%m-%d). Keep this file secret.
POSTGRES_PASSWORD=$(rand 32)
API_TOKEN=$(rand 40)
SITE_ADDRESS=$SITE
BASIC_AUTH_USER=$AUTH_USER
BASIC_AUTH_HASH='$HASH'
WORKER_CONCURRENCY=4

SCREENSHOT_ENABLED=true
ENRICHMENT_CONCURRENCY=4
ENRICHMENT_REFRESH_DAYS=7

# Collectors / AI / reports — fill in when you have them, then: sudo bash deploy/install.sh
APIFY_TOKEN=
SERP_API_KEY=
ANTHROPIC_API_KEY=
TELEGRAM_API_ID=
TELEGRAM_API_HASH=
TELEGRAM_BOT_TOKEN=
TELEGRAM_DIGEST_CHAT_ID=
EOF
  chmod 600 .env
else
  say "2/5 Mövcud .env saxlanılır."
fi
SITE=$(grep -E '^SITE_ADDRESS=' .env | cut -d= -f2-)

# 3. Build and start -------------------------------------------------------------
say "3/5 Servislər qurulur və işə salınır (ilk dəfə 5–15 dəqiqə çəkə bilər)…"
mkdir -p data/import backups
docker compose up -d --build

say "4/5 API-nin hazır olması gözlənilir…"
for i in $(seq 1 60); do
  if docker compose exec -T api python -c "import urllib.request,sys; urllib.request.urlopen('http://localhost:8000/api/health'); sys.exit(0)" >/dev/null 2>&1; then
    ok=1; break
  fi
  sleep 5
done
[ "${ok:-}" = 1 ] || die "API işə düşmədi. Loglara baxın: docker compose logs api"

# 4. Historical data -------------------------------------------------------------
SEED=$(ls -1 data/import/*.xlsx data/import/*.csv 2>/dev/null | head -1 || true)
FINDINGS=$(docker compose exec -T db psql -U radar -tAc "select count(*) from findings" 2>/dev/null || echo 0)
if [ -n "$SEED" ] && { [ "$FINDINGS" = "0" ] || [ "${1:-}" = "--import" ]; }; then
  say "5/5 Tarixi məlumat idxal olunur: $SEED"
  docker compose exec -T api radar import-seed "/data/import/$(basename "$SEED")" >/dev/null
  docker compose exec -T api radar report
  docker compose exec -T api radar enrich --queue
  echo "Domen zənginləşdirmə arxa planda başladı (ekran görüntüləri, WHOIS, DNS)."
elif [ -z "$SEED" ]; then
  say "5/5 data/import/ qovluğunda idxal faylı yoxdur — tarixi məlumat sonra əlavə oluna bilər."
else
  say "5/5 Məlumat artıq idxal olunub ($FINDINGS tapıntı)."
fi

# Daily backup at 03:10 server time, 14 days kept
CRON=/etc/cron.d/radar-backup
cat > "$CRON" <<EOF
10 3 * * * root cd $ROOT && docker compose exec -T db pg_dump -U radar -Fc radar > backups/radar-\$(date +\%F).dump && find backups -name '*.dump' -mtime +14 -delete
EOF
chmod 644 "$CRON"

IP=$(curl -fsS https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')
if [ "$SITE" = ":80" ]; then URL="http://$IP"; else URL="https://$SITE"; fi
say "Hazırdır: $URL"
echo "Kollektorların vəziyyəti:"
docker compose exec -T api radar collectors || true
